#include "bsp.h"
#include "bsp_i2c.h"
#include "bsp_csi.h"
#include "bsp_vl53l9.h"
#include "vl53l9_frame.h"
#include "delay.h"

#define I2C_SCL_HZ    400000           // I2C clock for the sensor control bus [Hz]
#define CSI_DATA_RATE 1000000000UL     // CSI-2 lane rate [bit/s], must match csi_config.phy_band
#define DSS_INDEX     6                // SPAD setting for every zone when DSS is off, 6 = most SPADs

// STEVAL-VL53L9 on the camera connector
// I2C2 on PB10/PB11, XSHUT PO5, AP_CLK PA0, SYNC_IN PG9, INTR PB13
vl53l9_i2c_t tof = {
    .i2c = &i2c2,
    .address = VL53L9_DEFAULT_7BIT_ADDRESS,
    .ext_clock = 12500000UL,           // AP_CLK generated by TIM2
    .vdda = VDDA_2V8,
    .vddio = VDDIO_1V8,
};

// 54x42 zones at 100 Hz with 4 ms exposure, DSS off
const tof_ranging_t tof_ranging = {
    .context = VL53L9_CONTEXT_SHORT,
    .power = VL53L9_POWER_REGULAR,
    .dss = VL53L9_DSS_DISABLE,
    .binning = 2,
    .exposure_ms = 4,
    .frame_period_us = 10000,
};

const char *tof_failed_step = "";      // name of the step that failed, empty on success

// 12.5 MHz AP_CLK on PA0 from TIM2
static void ap_clk_init(void)
{
    // enable clocks for GPIOA and TIM2
    RCC->AHB4ENR |= RCC_AHB4ENR_GPIOAEN;
    RCC->APB1ENR1 |= RCC_APB1ENR1_TIM2EN;

    // register read to make sure the clock is running
    (void)RCC->APB1ENR1;

    // 400 MHz / 32 = 12.5 MHz, output high for 16 of the 32 counts, then start
    TIM2->PSC = 0;
    TIM2->ARR = 32 - 1;
    TIM2->CCR1 = 16;
    TIM2->CCMR1 = (TIM2->CCMR1 & ~TIM_CCMR1_OC1M) | TIM_CCMR1_OC1M_2 | TIM_CCMR1_OC1M_1 | TIM_CCMR1_OC1FE;
    TIM2->CCER |= TIM_CCER_CC1E;
    TIM2->EGR = TIM_EGR_UG;
    TIM2->CR1 |= TIM_CR1_CEN;

    // PA0 in alternate function mode, AF1 = TIM2_CH1, very high speed
    GPIOA->OSPEEDR |= GPIO_OSPEEDR_OSPEED0;
    GPIOA->AFR[0] = (GPIOA->AFR[0] & ~GPIO_AFRL_AFSEL0) | (1 << GPIO_AFRL_AFSEL0_Pos);
    GPIOA->MODER = (GPIOA->MODER & ~GPIO_MODER_MODE0) | GPIO_MODER_MODE0_1;
}

// XSHUT, SYNC_IN and INTR pins
static void control_pins_init(void)
{
    // enable clocks for GPIOB, GPIOG, GPIOO and PWR
    RCC->AHB4ENR |= RCC_AHB4ENR_GPIOBEN | RCC_AHB4ENR_GPIOGEN | RCC_AHB4ENR_GPIOOEN | RCC_AHB4ENR_PWREN;
    (void)RCC->AHB4ENR;

    // enable the VDDIO2 supply for port O
    PWR->SVMCR3 |= PWR_SVMCR3_VDDIO2SV;

    // PO5 (XSHUT) output, low holds the sensor in reset
    GPIOO->BSRR = GPIO_BSRR_BR5;
    GPIOO->MODER = (GPIOO->MODER & ~GPIO_MODER_MODE5) | GPIO_MODER_MODE5_0;

    // PG9 (SYNC_IN) output high, unused
    GPIOG->BSRR = GPIO_BSRR_BS9;
    GPIOG->MODER = (GPIOG->MODER & ~GPIO_MODER_MODE9) | GPIO_MODER_MODE9_0;

    // PB13 (INTR) input, unused
    GPIOB->MODER &= ~GPIO_MODER_MODE13;
}

// saves the name of the failed step and returns its error code
static int fail(const char *step, int ret)
{
    tof_failed_step = step;
    return ret;
}

// boots the sensor, sets up ranging and CSI-2 and starts streaming, needs clock_init
int tof_init(void)
{
    const tof_ranging_t *r = &tof_ranging;
    int ret;

    // the sensor needs AP_CLK running before it leaves reset
    ap_clk_init();
    control_pins_init();
    i2c2_init(I2C_SCL_HZ);

    // reset the sensor, XSHUT low for 50 ms then wait 50 ms for it to boot
    GPIOO->BSRR = GPIO_BSRR_BR5;
    delay_ms(50);
    GPIOO->BSRR = GPIO_BSRR_BS5;
    delay_ms(50);

    // load the firmware patch and default settings
    if ((ret = vl53l9_init(&tof)) != VL53L9_ERROR_NONE)
    {
        return fail("init", ret);
    }

    // ranging settings, the context has to be set before binning
    if ((ret = vl53l9_set_sync_mode(&tof, VL53L9_SYNC_AUTONOMOUS)) != VL53L9_ERROR_NONE
        || (ret = vl53l9_set_power_mode(&tof, r->power)) != VL53L9_ERROR_NONE
        || (ret = vl53l9_set_frame_period(&tof, r->frame_period_us)) != VL53L9_ERROR_NONE
        || (ret = vl53l9_set_context(&tof, r->context)) != VL53L9_ERROR_NONE
        || (ret = vl53l9_set_binning(&tof, r->context, r->binning)) != VL53L9_ERROR_NONE
        || (ret = vl53l9_set_exposure(&tof, r->context, r->exposure_ms)) != VL53L9_ERROR_NONE
        || (ret = vl53l9_set_dss(&tof, r->context, r->dss)) != VL53L9_ERROR_NONE
        || (ret = vl53l9_set_dss_default_index(&tof, DSS_INDEX)) != VL53L9_ERROR_NONE)
    {
        return fail("ranging", ret);
    }

    // CSI-2 output settings, the frame height does not include the status line
    vl53l9_hw_config_t hw;
    if ((ret = vl53l9_get_hw_config(&tof, &hw)) != VL53L9_ERROR_NONE)
    {
        return fail("get_hw_config", ret);
    }
    hw.output_interface = VL53L9_OUTPUT_CSI2;
    hw.signaling_mode = true;
    hw.csi_data_rate = CSI_DATA_RATE;
    hw.csi_virtual_channel = 0;
    hw.csi_status_line_force_width = false;
    hw.csi_status_line_datatype = VL53L9_CSI_DATA_TYPE;
    hw.csi_frame_datatype = VL53L9_CSI_DATA_TYPE;
    hw.csi_frame_height = vl53l9_frame_lines(r->binning, r->dss) - 1;
    hw.csi_frame_width = VL53L9_CSI_LINE_SIZE;
    if ((ret = vl53l9_set_hw_config(&tof, hw)) != VL53L9_ERROR_NONE)
    {
        return fail("set_hw_config", ret);
    }

    // arm the receiver before the sensor starts streaming
    csi_board_init();
    if (csi_start(&csi) != 0)
    {
        return fail("csi_start", TOF_ERR_CSI);
    }

    if ((ret = vl53l9_start(&tof)) != VL53L9_ERROR_NONE)
    {
        return fail("start", ret);
    }
    return VL53L9_ERROR_NONE;
}
